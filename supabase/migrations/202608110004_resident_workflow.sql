-- Resident work logs, immutable edit history, delivery tracking, and doctor objections.
-- Financial policy: consultations/births/cesareans are calculated immediately.
-- Inpatient compensation remains pending until Accounts confirms paid inpatient days.

alter table public.doctor_calls
  add column if not exists call_hours integer not null default 12
    check (call_hours in (12, 24)),
  add column if not exists inpatient_count integer not null default 0
    check (inpatient_count >= 0),
  add column if not exists consultation_count integer not null default 0
    check (consultation_count >= 0),
  add column if not exists natural_birth_count integer not null default 0
    check (natural_birth_count >= 0),
  add column if not exists cesarean_count integer not null default 0
    check (cesarean_count >= 0),
  add column if not exists special_cases_count integer not null default 0
    check (special_cases_count >= 0),
  add column if not exists special_cases_note text,
  add column if not exists last_edited_by bigint references public.employees(id) on delete set null,
  add column if not exists last_edited_by_name text;

create table if not exists public.doctor_call_consultations (
  id bigint generated by default as identity primary key,
  call_id bigint not null references public.doctor_calls(id) on delete cascade,
  case_number integer not null check (case_number > 0),
  case_label text,
  evidence_path text not null,
  amount numeric(14, 2) not null default 10000 check (amount >= 0),
  created_by bigint references public.employees(id) on delete set null,
  created_by_name text not null,
  created_at timestamptz not null default now(),
  unique (call_id, case_number)
);

create table if not exists public.doctor_call_revisions (
  id bigint generated by default as identity primary key,
  call_id bigint not null references public.doctor_calls(id) on delete cascade,
  editor_id bigint references public.employees(id) on delete set null,
  editor_name text not null,
  action text not null check (action in ('إنشاء', 'تعديل', 'تسوية اعتراض')),
  before_data jsonb,
  after_data jsonb not null,
  financial_delta numeric(14, 2) not null default 0,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.doctor_call_deliveries (
  id bigint generated by default as identity primary key,
  call_id bigint not null references public.doctor_calls(id) on delete cascade,
  recipient_role text not null check (recipient_role in ('الحسابات', 'رئيس المقيمين', 'الإدارة العليا')),
  status text not null default 'تم الإرسال' check (status in ('تم الإرسال', 'تم الاطلاع')),
  sent_at timestamptz not null default now(),
  viewed_at timestamptz,
  unique (call_id, recipient_role)
);

create table if not exists public.doctor_call_objections (
  id bigint generated by default as identity primary key,
  call_id bigint not null references public.doctor_calls(id) on delete cascade,
  doctor_id bigint not null references public.employees(id) on delete restrict,
  doctor_name text not null,
  reason text not null,
  disputed_amount numeric(14, 2) not null check (disputed_amount > 0),
  status text not null default 'مرسل'
    check (status in ('مرسل', 'قيد التدقيق', 'تم التدقيق', 'مرفوض')),
  reviewer_id bigint references public.employees(id) on delete set null,
  reviewer_name text,
  response_note text,
  adjustment_amount numeric(14, 2) not null default 0,
  submitted_at timestamptz not null default now(),
  resolved_at timestamptz,
  updated_at timestamptz not null default now()
);

create index if not exists idx_call_consultations_call
  on public.doctor_call_consultations (call_id, case_number);
create index if not exists idx_call_revisions_call
  on public.doctor_call_revisions (call_id, created_at desc);
create index if not exists idx_call_deliveries_recipient
  on public.doctor_call_deliveries (recipient_role, status, sent_at desc);
create index if not exists idx_call_objections_status
  on public.doctor_call_objections (status, submitted_at desc);
create index if not exists idx_doctor_calls_last_editor
  on public.doctor_calls (last_edited_by_name, updated_at desc);

drop trigger if exists set_doctor_call_objections_updated_at on public.doctor_call_objections;
create trigger set_doctor_call_objections_updated_at
  before update on public.doctor_call_objections
  for each row execute function public.set_updated_at();

