-- Staff presence, durable file metadata, operational tasks, and Telegram bot integration.
-- All runtime access remains server-side through the Supabase service role.

create table if not exists public.file_attachments (
  id bigint generated by default as identity primary key,
  bucket_name text not null,
  object_path text not null,
  entity_type text not null check (entity_type in ('patient', 'employee', 'doctor_call', 'task', 'report')),
  entity_id text not null,
  category text not null,
  original_filename text not null,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes > 0),
  checksum_sha256 text,
  uploaded_by bigint references public.employees(id) on delete set null,
  uploaded_by_name text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (bucket_name, object_path)
);

create table if not exists public.employee_attendance_sessions (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete restrict,
  clock_in_at timestamptz not null default now(),
  clock_out_at timestamptz,
  clock_in_source text not null default 'web'
    check (clock_in_source in ('web', 'telegram', 'admin', 'system')),
  clock_out_source text
    check (clock_out_source is null or clock_out_source in ('web', 'telegram', 'admin', 'system')),
  clock_in_note text,
  clock_out_note text,
  created_by bigint references public.employees(id) on delete set null,
  created_at timestamptz not null default now(),
  check (clock_out_at is null or clock_out_at >= clock_in_at)
);

create table if not exists public.employee_activity_events (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  employee_name text not null,
  employee_role text not null,
  activity_type text not null,
  entity_type text,
  entity_id text,
  description text not null,
  source text not null default 'web'
    check (source in ('web', 'telegram', 'admin', 'system')),
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create table if not exists public.operational_tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  assigned_employee_id bigint not null references public.employees(id) on delete restrict,
  related_patient_id bigint references public.patients(id) on delete set null,
  status text not null default 'مفتوحة'
    check (status in ('مفتوحة', 'قيد المتابعة', 'مكتملة', 'ملغاة')),
  priority text not null default 'اعتيادية'
    check (priority in ('اعتيادية', 'مهمة', 'عاجلة')),
  due_at timestamptz,
  created_by bigint references public.employees(id) on delete set null,
  completed_by bigint references public.employees(id) on delete set null,
  source text not null default 'web'
    check (source in ('web', 'telegram', 'admin', 'system')),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.telegram_accounts (
  id bigint generated by default as identity primary key,
  employee_id bigint not null unique references public.employees(id) on delete cascade,
  telegram_user_id bigint not null unique,
  chat_id bigint not null unique,
  username text,
  display_name text,
  status text not null default 'معتمد'
    check (status in ('بانتظار الموافقة', 'معتمد', 'محظور')),
  paired_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.telegram_link_codes (
  id bigint generated by default as identity primary key,
  code text not null unique,
  employee_id bigint not null references public.employees(id) on delete cascade,
  created_by bigint references public.employees(id) on delete set null,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now(),
  check (expires_at > created_at)
);

create table if not exists public.telegram_updates (
  update_id bigint primary key,
  chat_id bigint,
  employee_id bigint references public.employees(id) on delete set null,
  command text,
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'مستلم'
    check (status in ('مستلم', 'تمت المعالجة', 'فشل')),
  error_message text,
  received_at timestamptz not null default now(),
  processed_at timestamptz
);

create unique index if not exists idx_attendance_one_open_session
  on public.employee_attendance_sessions (employee_id)
  where clock_out_at is null;
create index if not exists idx_attendance_clock_in
  on public.employee_attendance_sessions (clock_in_at desc);
create index if not exists idx_attendance_employee_history
  on public.employee_attendance_sessions (employee_id, clock_in_at desc);
create index if not exists idx_employee_activity_latest
  on public.employee_activity_events (employee_id, occurred_at desc);
create index if not exists idx_employee_activity_entity
  on public.employee_activity_events (entity_type, entity_id, occurred_at desc);
create index if not exists idx_operational_tasks_assignee
  on public.operational_tasks (assigned_employee_id, status, due_at);
create index if not exists idx_telegram_updates_received
  on public.telegram_updates (received_at desc);
create index if not exists idx_file_attachments_entity
  on public.file_attachments (entity_type, entity_id, created_at desc);

