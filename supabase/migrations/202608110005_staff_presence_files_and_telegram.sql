create or replace function public.record_attendance_event(
  p_employee_name text,
  p_action text,
  p_source text default 'web',
  p_note text default null,
  p_recorded_by_name text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  employee_record public.employees%rowtype;
  recorder_record public.employees%rowtype;
  session_record public.employee_attendance_sessions%rowtype;
  activity_description text;
begin
  if p_source not in ('web', 'telegram', 'admin', 'system') then
    raise exception 'Unsupported attendance source';
  end if;
  if p_action not in ('دخول', 'خروج') then
    raise exception 'Unsupported attendance action';
  end if;

  select * into employee_record
  from public.employees
  where full_name = trim(p_employee_name) and status = 'نشط'
  order by id limit 1;
  if employee_record.id is null then raise exception 'Employee not found'; end if;

  select * into recorder_record
  from public.employees
  where full_name = trim(coalesce(nullif(p_recorded_by_name, ''), p_employee_name)) and status = 'نشط'
  order by id limit 1;

  if p_action = 'دخول' then
    select * into session_record
    from public.employee_attendance_sessions
    where employee_id = employee_record.id and clock_out_at is null
    order by clock_in_at desc limit 1 for update;
    if session_record.id is not null then raise exception 'Employee already clocked in'; end if;

    insert into public.employee_attendance_sessions (
      employee_id, clock_in_source, clock_in_note, created_by
    ) values (
      employee_record.id, p_source, nullif(trim(p_note), ''), coalesce(recorder_record.id, employee_record.id)
    ) returning * into session_record;
    activity_description := 'سجّل الحضور إلى المستشفى';
  else
    select * into session_record
    from public.employee_attendance_sessions
    where employee_id = employee_record.id and clock_out_at is null
    order by clock_in_at desc limit 1 for update;
    if session_record.id is null then raise exception 'Employee is not clocked in'; end if;

    update public.employee_attendance_sessions set
      clock_out_at = now(),
      clock_out_source = p_source,
      clock_out_note = nullif(trim(p_note), '')
    where id = session_record.id
    returning * into session_record;
    activity_description := 'سجّل الانصراف من المستشفى';
  end if;

  insert into public.employee_activity_events (
    employee_id, employee_name, employee_role, activity_type, entity_type,
    entity_id, description, source, metadata
  ) values (
    employee_record.id, employee_record.full_name, employee_record.role,
    'حضور وانصراف', 'attendance_session', session_record.id::text,
    activity_description, p_source,
    jsonb_build_object('action', p_action, 'recordedBy', coalesce(recorder_record.full_name, employee_record.full_name))
  );

  insert into public.audit_logs (actor_id, action, entity_type, entity_id, after_data)
  values (
    coalesce(recorder_record.id, employee_record.id), 'تسجيل ' || p_action,
    'attendance_session', session_record.id::text,
    jsonb_build_object('employeeId', employee_record.id, 'employeeName', employee_record.full_name, 'source', p_source)
  );

  return jsonb_build_object(
    'id', session_record.id,
    'employeeId', employee_record.id,
    'employeeName', employee_record.full_name,
    'role', employee_record.role,
    'clockInAt', session_record.clock_in_at,
    'clockOutAt', session_record.clock_out_at,
    'isPresent', session_record.clock_out_at is null
  );
end;
$$;

create or replace function public.record_employee_activity(
  p_employee_name text,
  p_activity_type text,
  p_description text,
  p_entity_type text default null,
  p_entity_id text default null,
  p_source text default 'web',
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  employee_record public.employees%rowtype;
  activity_record public.employee_activity_events%rowtype;
begin
  if p_source not in ('web', 'telegram', 'admin', 'system') then
    raise exception 'Unsupported activity source';
  end if;
  select * into employee_record
  from public.employees
  where full_name = trim(p_employee_name) and status = 'نشط'
  order by id limit 1;
  if employee_record.id is null then raise exception 'Employee not found'; end if;

  insert into public.employee_activity_events (
    employee_id, employee_name, employee_role, activity_type,
    entity_type, entity_id, description, source, metadata
  ) values (
    employee_record.id, employee_record.full_name, employee_record.role,
    trim(p_activity_type), nullif(trim(p_entity_type), ''), nullif(trim(p_entity_id), ''),
    trim(p_description), p_source, coalesce(p_metadata, '{}'::jsonb)
  ) returning * into activity_record;

  return jsonb_build_object('id', activity_record.id, 'occurredAt', activity_record.occurred_at);
end;
$$;

create or replace view public.employee_presence_overview
with (security_invoker = true)
as
select
  employee.id as employee_id,
  employee.full_name,
  employee.role,
  employee.specialty,
  employee.status as employee_status,
  (open_session.id is not null) as is_present,
  open_session.id as attendance_session_id,
  open_session.clock_in_at,
  open_session.clock_in_source,
  open_session.clock_in_note,
  last_activity.activity_type as last_activity_type,
  last_activity.description as last_activity,
  last_activity.source as last_activity_source,
  last_activity.occurred_at as last_activity_at,
  telegram.status as telegram_status,
  telegram.username as telegram_username,
  telegram.last_seen_at as telegram_last_seen_at
from public.employees employee
left join lateral (
  select attendance.*
  from public.employee_attendance_sessions attendance
  where attendance.employee_id = employee.id and attendance.clock_out_at is null
  order by attendance.clock_in_at desc
  limit 1
) open_session on true
left join lateral (
  select activity.activity_type, activity.description, activity.source, activity.occurred_at
  from public.employee_activity_events activity
  where activity.employee_id = employee.id
  order by activity.occurred_at desc
  limit 1
) last_activity on true
left join public.telegram_accounts telegram on telegram.employee_id = employee.id
where employee.status = 'نشط';

do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values
      ('patient-files', 'patient-files', false, 15728640,
        array['image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif', 'application/pdf']),
      ('employee-files', 'employee-files', false, 10485760,
        array['image/jpeg', 'image/png', 'image/webp', 'application/pdf']),
      ('system-exports', 'system-exports', false, 26214400,
        array['application/pdf', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'text/csv'])
    on conflict (id) do update
    set public = false,
        file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types;
  end if;
end $$;

