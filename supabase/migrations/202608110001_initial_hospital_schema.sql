create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array['employees', 'patients', 'procedures', 'doctor_calls', 'inpatient_payments', 'doctor_caps']
  loop
    execute format('drop trigger if exists set_%I_updated_at on public.%I', table_name, table_name);
    execute format('create trigger set_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()', table_name, table_name);
  end loop;
end;
$$;

create or replace function public.register_patient(
  p_full_name text,
  p_file_number text,
  p_birth_date date,
  p_gender text,
  p_phone text,
  p_admission_date date,
  p_department text,
  p_attending_doctor text,
  p_payment_category text,
  p_entry_type text,
  p_billing_mode text,
  p_notes text,
  p_initial_price numeric,
  p_newborn_names jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  mother public.patients%rowtype;
  newborn_name text;
  newborn_index bigint;
  newborn_total integer := jsonb_array_length(coalesce(p_newborn_names, '[]'::jsonb));
begin
  insert into public.patients (
    full_name, file_number, birth_date, gender, phone, admission_date,
    department, attending_doctor, payment_category, entry_type, billing_mode, notes
  ) values (
    trim(p_full_name), trim(p_file_number), p_birth_date, trim(p_gender), nullif(trim(p_phone), ''),
    p_admission_date, trim(p_department), nullif(trim(p_attending_doctor), ''),
    coalesce(nullif(trim(p_payment_category), ''), 'نقدي'),
    coalesce(nullif(trim(p_entry_type), ''), 'استشارية'),
    coalesce(nullif(trim(p_billing_mode), ''), 'مقطوعي'), nullif(trim(p_notes), '')
  ) returning * into mother;

  for newborn_name, newborn_index in
    select value, ordinality
    from jsonb_array_elements_text(coalesce(p_newborn_names, '[]'::jsonb)) with ordinality
  loop
    insert into public.patients (
      full_name, file_number, gender, admission_date, department, attending_doctor,
      payment_category, entry_type, billing_mode, is_newborn, mother_id, twin_order
    ) values (
      newborn_name, p_file_number || '-N' || newborn_index, 'غير محدد', p_admission_date,
      'حديثو الولادة', nullif(trim(p_attending_doctor), ''),
      coalesce(nullif(trim(p_payment_category), ''), 'نقدي'), 'مولود جديد',
      'مرتبط بملف الأم', true, mother.id,
      case when newborn_total > 1 then newborn_index::integer else null end
    );
  end loop;

  insert into public.patient_events (patient_id, event_type, amount)
  values (mother.id, p_entry_type, greatest(coalesce(p_initial_price, 0), 0));

  insert into public.audit_logs (action, entity_type, entity_id, after_data)
  values ('register', 'patient', mother.id::text, to_jsonb(mother));

  return jsonb_build_object(
    'record', to_jsonb(mother) || jsonb_build_object('newborn_count', newborn_total),
    'newborn_names', coalesce(p_newborn_names, '[]'::jsonb)
  );
end;
$$;

create or replace function public.transition_patient_lifecycle(
  p_patient_id bigint,
  p_action text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  patient_record public.patients%rowtype;
  result_message text;
begin
  if p_action = 'convert_to_inpatient' then
    update public.patient_events
    set is_invalidated = true,
        invalidated_reason = 'تم التحول إلى رقود'
    where patient_id = p_patient_id
      and event_type in ('ولادة طبيعية', 'عملية قيصرية')
      and is_invalidated = false;

    update public.call_details details
    set is_invalidated = true,
        invalidated_reason = 'تم التحول إلى رقود'
    from public.procedures procedures
    where details.patient_id = p_patient_id
      and details.procedure_id = procedures.id
      and procedures.name in ('ولادة طبيعية', 'عملية قيصرية')
      and details.is_invalidated = false;

    update public.patients
    set entry_type = 'رقود', billing_mode = 'تراكمي'
    where id = p_patient_id
    returning * into patient_record;

    if patient_record.id is null then
      raise exception 'Patient not found';
    end if;

    insert into public.patient_events (patient_id, event_type, amount)
    values (p_patient_id, 'رقود', 0);
    result_message := 'أُلغيت تسعيرة الولادة وبدأ احتساب الرقود التراكمي';
  elsif p_action = 'discharge' then
    update public.patients
    set patient_status = 'خرجت', discharge_date = current_date
    where id = p_patient_id
    returning * into patient_record;

    if patient_record.id is null then
      raise exception 'Patient not found';
    end if;

    insert into public.patient_events (patient_id, event_type, amount)
    values (p_patient_id, 'خروج المريضة', 0);
    result_message := 'أُغلق الملف بعد المراجعة النهائية';
  else
    raise exception 'Unsupported lifecycle action';
  end if;

  insert into public.audit_logs (action, entity_type, entity_id, after_data)
  values (p_action, 'patient', p_patient_id::text, to_jsonb(patient_record));

  return jsonb_build_object('patient', to_jsonb(patient_record), 'message', result_message);
end;
$$;

