-- Al-Bayati Hospital: production PostgreSQL schema
-- Safe to run more than once. Runtime access is restricted to the server-side service role.

create extension if not exists pgcrypto;

create table if not exists public.app_schema_migrations (
  version text primary key,
  applied_at timestamptz not null default now()
);

create table if not exists public.employees (
  id bigint generated by default as identity primary key,
  full_name text not null,
  employee_number text not null unique,
  username text not null unique,
  phone text,
  role text not null,
  specialty text not null,
  join_date date not null,
  max_consultations integer check (max_consultations is null or max_consultations >= 0),
  daily_cap numeric(14, 2) check (daily_cap is null or daily_cap >= 0),
  status text not null default 'نشط',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.patients (
  id bigint generated by default as identity primary key,
  full_name text not null,
  file_number text not null unique,
  birth_date date,
  gender text not null,
  phone text,
  admission_date date not null,
  department text not null,
  attending_doctor text,
  payment_category text not null default 'نقدي',
  entry_type text not null default 'استشارية',
  patient_status text not null default 'نشط',
  billing_mode text not null default 'مقطوعي',
  is_newborn boolean not null default false,
  mother_id bigint references public.patients(id) on delete restrict,
  twin_order integer check (twin_order is null or twin_order > 0),
  discharge_date date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((is_newborn = false and mother_id is null) or (is_newborn = true and mother_id is not null))
);

create table if not exists public.patient_events (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(id) on delete restrict,
  event_type text not null,
  amount numeric(14, 2) not null default 0 check (amount >= 0),
  is_invalidated boolean not null default false,
  invalidated_reason text,
  created_at timestamptz not null default now()
);

create table if not exists public.procedures (
  id bigint generated by default as identity primary key,
  name text not null unique,
  base_price numeric(14, 2) not null default 0 check (base_price >= 0),
  category text not null default 'خاضع للسقف',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.doctor_calls (
  id bigint generated by default as identity primary key,
  doctor_id bigint not null references public.employees(id) on delete restrict,
  call_date date not null,
  status text not null default 'قيد الإدخال',
  total_calculated numeric(14, 2) not null default 0 check (total_calculated >= 0),
  total_approved numeric(14, 2) not null default 0 check (total_approved >= 0),
  submitted_at timestamptz,
  approved_at timestamptz,
  approved_by bigint references public.employees(id) on delete restrict,
  review_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (doctor_id, call_date)
);

create table if not exists public.call_details (
  id bigint generated by default as identity primary key,
  call_id bigint not null references public.doctor_calls(id) on delete cascade,
  patient_id bigint not null references public.patients(id) on delete restrict,
  procedure_id bigint not null references public.procedures(id) on delete restrict,
  quantity integer not null default 1 check (quantity > 0),
  amount numeric(14, 2) not null check (amount >= 0),
  attachment_url text,
  is_invalidated boolean not null default false,
  invalidated_reason text,
  created_at timestamptz not null default now()
);

create table if not exists public.inpatient_payments (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(id) on delete restrict,
  record_date date not null,
  payment_status text not null default 'ليس بعد',
  updated_by bigint references public.employees(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (patient_id, record_date)
);

create table if not exists public.doctor_caps (
  id bigint generated by default as identity primary key,
  doctor_id bigint not null unique references public.employees(id) on delete cascade,
  max_consultations integer not null default 10 check (max_consultations >= 0),
  max_daily_amount numeric(14, 2) not null default 200000 check (max_daily_amount >= 0),
  updated_by bigint references public.employees(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id bigint references public.employees(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);

